/**
 * @file 로고 픽셀 그림 (logo.ts)
 *
 * 이 파일이 하는 일
 *   블로그 로고(필름 릴 두 개를 얹은 옛 영화 카메라)를 글자 격자로 그려 둡니다.
 *
 *     .##...##....   ← 필름 릴 두 개(가운데가 빈 동그라미)
 *     #..#.#..#...
 *     #..#.#..#...
 *     .##...##....
 *     #########..#   ← 카메라 몸통(속이 빈 네모)과 오른쪽 렌즈(나팔 모양)
 *     #.......#.##
 *     #.......####
 *     #.......####
 *     #.......#.##
 *     #########..#
 *
 * 그림이 두 가지예요(같은 카메라예요)
 *   - LOGO_ROWS(12 × 10칸)        : scripts/make-icons.mjs가 브라우저 탭 아이콘(src/app/icon.svg),
 *                                  설치 앱 아이콘(public/icons/*.png), 공유 미리 보기 그림(public/og.png)을 만들 때 써요.
 *                                  (그림을 고친 뒤에는 `pnpm icons`를 실행해 아이콘 파일을 다시 만들어요.)
 *   - HEADER_LOGO_ROWS(12 × 12칸) : components/site-header.tsx가 머리글 왼쪽에 그려요.
 *                                  LOGO_ROWS 위아래에 빈 줄을 하나씩 더해, 오른쪽 GitHub 아이콘(lib/github-mark.ts)과
 *                                  같은 12칸 격자로 맞췄어요. 한 칸 2px로 그리면 둘 다 24 × 24px로 크기가 같아요.
 *   머리글 그림은 LOGO_ROWS로 만들어서, 모양을 바꿀 때는 LOGO_ROWS만 고치면 돼요.
 *
 * 그림 읽는 법
 *   '#'은 색칠한 칸, '.'은 빈칸이에요.
 *   왼쪽 끝 칸(카메라 몸통)과 오른쪽 끝 칸(렌즈)이 색칠돼 있어서, 그림 끝이 곧 요소 끝이에요(머리글의 로고 ↔ 이름 간격이 그대로예요).
 *
 * 이 파일에는 화면 코드(JSX)를 넣지 않아요. 아이콘 스크립트(Node.js)도 그대로 불러 쓸 수 있게 하려는 거예요.
 */

/** 로고(12 × 10칸): 필름 릴 두 개를 얹은 옛 영화 카메라. 아이콘 스크립트가 아이콘 가운데에 놓아 써요. */
export const LOGO_ROWS = [
  ".##...##....",
  "#..#.#..#...",
  "#..#.#..#...",
  ".##...##....",
  "#########..#",
  "#.......#.##",
  "#.......####",
  "#.......####",
  "#.......#.##",
  "#########..#",
] as const;

/** 빈 줄(12칸). 머리글 그림의 위아래에 하나씩 더해요. */
const BLANK_ROW = "............";

/** 머리글 로고(12 × 12칸). LOGO_ROWS 위아래에 빈 줄을 하나씩 더해 GitHub 아이콘과 같은 크기로 맞춰요. */
export const HEADER_LOGO_ROWS = [BLANK_ROW, ...LOGO_ROWS, BLANK_ROW] as const;
